"""Contract cases of `runtime.actions`, the projection the Dashboard renders every timed action from (roadmap item 6, batch 2: r17a).

ONE new family of dashboard_contract_pages_v1.json, `battle_actions_projection`, generated by the real route (GET /api/battles/active) over a run driver the way the orchestrator builds one:
the real `BattleSession` with the real `ActionSession` attached, the real gem collectors and shopper holding that session's recorders, on the world's fixed clock. Nothing here is typed by hand:
`battle.runtime.actions` is what `ActionSession.project` builds from the routines the bindings publish, and every other field of the read is the ledger's.

The page renders an action from its item alone (no branch per action): `id`, `instance`, `label`, `state` (disabled | waiting | due | running), `enabled`, `eligibility.blocker`, `last` (the newest
finished execution: result, reason, effect, trigger, start, finish, duration), `active.window_ends_at`, `next` (due_at, basis, with unknown as null plus a reason), the `descriptor`
(fields with type, bounds, unit, live / saved / nullable; capabilities; variants), `values`, `counters`, `coverage`; and the envelope: `schema_version`, `ledger_id`, `control_revision`,
`context`, `published_at`, `observed_at`. A battle whose driver cannot build the projection publishes `runtime.routines` and, until a projection has been built once, no `actions` key at all.

  idle                       ad gems and floating gems due at once (the first window of start-to-start, the first sighting of appearance-driven), shopping waiting for its interval;
  ad window open             the ad collector's window is open: state running with `active.window_ends_at`;
  last execution             a finished execution (written through the session's recorder, as the collectors do) is `last` of its instance, with its effect;
  paused by a control        a live control through the real checkpoint switches ad gems off: state disabled, enabled false;
  not visible                the game is not on screen: every routine carries blocker waiting_for_game_state and the projection says so;
  shopping gate off          shopping disabled by a control: state disabled;
  projection unavailable     the projection could not be built: from the first publish on there is no `actions` key; after a successful one the LAST projection stays (the ledger merges what a
                             publish writes) with its own `observed_at`, which then stops advancing while `server_time` of the routines moves on: staleness is readable, never silent.

Not recorded (no producer in this build): a `schema_version` newer than the reader knows (only a newer driver writes one) and the descriptor of an action the catalog does not hold (the synthetic extension
is proved through the real routes in test_action_synthetic_extension.py; it is test-local and is not part of the production contract).
"""
from types import SimpleNamespace

from flows.shard import GemWatch
from runtime.action_session import ActionSession

from dashboard_contract_cases_run_leftovers import active
from test_dashboard_contract import PLAN_V2, Driver, with_orbit, with_shopping

BP = 'battle_actions_projection'


def attach(driver):
    """What the orchestrator does at start: an ActionSession for the battle, the gem collectors and the shopper holding its recorders."""
    session = ActionSession.for_battle(driver.session, 'orchestrator')
    session.clock = SimpleNamespace(mono=driver.w.clock.monotonic, wall=driver.w.clock.time)      # the session reads mono() and wall(); the world's clock names them monotonic() and time()
    gather = driver.session.base_preset['gather']
    driver.rs.gems = GemWatch(gather, session=session)
    driver.rs.shop.recorder = session.recorder('shopping')
    return session


def read(w, case):
    return active(w, BP, case).get_json()['battle']['runtime']


def items(runtime):
    return {item['id']: item for item in runtime['actions']['items']}


def battle_actions_projection_cases(gen):
    with gen.world('actions_projection') as w:
        w.edit_profile(with_orbit)
        w.edit_profile(with_shopping(PLAN_V2))
        d = Driver(w, 'projected', origin='started')
        session = attach(d)
        d.observe()
        d.publish()
        idle = read(w, 'idle_ad_and_floating_gems_due_shopping_waiting')
        shown = items(idle)
        assert [item['id'] for item in idle['actions']['items']] == ['ad_gems', 'floating_gems', 'shopping'], list(shown)
        assert (shown['ad_gems']['state'], shown['floating_gems']['state'], shown['shopping']['state']) == ('due', 'due', 'waiting'), {k: v['state'] for k, v in shown.items()}
        assert shown['ad_gems']['next']['basis'] == 'start_to_start' and shown['floating_gems']['next']['basis'] == 'appearance_driven' and shown['shopping']['next']['basis'] == 'after_completion'
        assert idle['actions']['schema_version'] == 1 and idle['actions']['ledger_id'] and idle['actions']['control_revision'] == 0 and idle['actions']['context']['profile']
        assert all(item['last'] is None and item['active'] is None and item['coverage'] == 'full' for item in shown.values())
        assert {name: [field['path'] for field in item['descriptor']['fields']] for name, item in shown.items()} == {
            'ad_gems': ['enabled', 'interval_sec', 'window_sec'], 'floating_gems': ['enabled', 'interval_sec', 'window_sec', 'tap_interval_sec'], 'shopping': ['enabled', 'interval_sec']}
        assert all(item['descriptor']['variants'] == [] for item in shown.values()), 'variants are published once, in capabilities.actions'
        assert set(idle['routines']) >= {'ad_gems', 'floating_gems', 'shopping'}
        ad = d.rs.gems.ad_gems
        ad.window_started_at, ad.window_deadline = w.clock.monotonic() - 5, w.clock.monotonic() + 20
        d.publish()
        running = read(w, 'ad_window_open_is_running')
        assert items(running)['ad_gems']['state'] == 'running' and items(running)['ad_gems']['active']['window_ends_at'] is not None
        ad.window_started_at = ad.window_deadline = None
        window = session.begin('ad_gems', occurrence_key='window:projected')
        w.advance(4)
        session.finish(window, result='succeeded', reason='offer_disappeared', effect='confirmed', attempts=1, confirmed=1, evidence=['offer_disappeared'])
        d.publish()
        finished = read(w, 'a_finished_execution_is_the_last_of_its_instance')
        last = items(finished)['ad_gems']['last']
        assert (last['result'], last['reason'], last['effect'], last['trigger']) == ('succeeded', 'offer_disappeared', 'confirmed', 'automatic') and last['duration_ms'] == 4000.0
        assert items(finished)['floating_gems']['last'] is None
        d.controls({'routines': {'ad_gems': {'enabled': False}}}, 'pause-ad-gems')
        d.checkpoint()
        paused = read(w, 'ad_gems_paused_by_a_control_is_disabled')
        assert items(paused)['ad_gems']['state'] == 'disabled' and items(paused)['ad_gems']['enabled'] is False and paused['actions']['control_revision'] == 1
        d.controls({'routines': {'shopping': {'enabled': False}}}, 'pause-shopping')
        d.checkpoint()
        assert items(read(w, 'shopping_switched_off_by_a_control_is_disabled'))['shopping']['state'] == 'disabled'
        d.publish(visible=False)
        hidden = read(w, 'game_not_on_screen_every_routine_waits_for_the_game_state')
        assert hidden['observation_status'] == 'waiting_for_game_state' and {item['eligibility']['blocker'] for item in hidden['actions']['items']} == {'waiting_for_game_state'}
        before = hidden['actions']
        w.mp.setattr(session, 'project', lambda *args, **kwargs: (_ for _ in ()).throw(RuntimeError('the projection cannot be built')))
        d.publish()
        stale = read(w, 'projection_fails_later_the_last_projection_stays_and_its_stamps_stop')
        assert stale['actions'] == before and stale['actions']['observed_at'] < stale['server_time'] and stale['routines']['ad_gems']['server_time'] == stale['server_time']
    with gen.world('actions_projection_never') as w:
        d = Driver(w, 'never', origin='started')
        session = attach(d)
        w.mp.setattr(session, 'project', lambda *args, **kwargs: (_ for _ in ()).throw(RuntimeError('the projection cannot be built')))
        d.observe()
        d.publish()
        broken = read(w, 'projection_never_built_the_actions_key_is_absent')
        assert 'actions' not in broken and set(broken['routines']) >= {'ad_gems', 'floating_gems', 'shopping'}


