"""Contract cases of GET /api/calibrate/metrics (roadmap item 9, package p9a): what one calibration measured and its operation sealed.

ONE new family of dashboard_contract_pages_v1.json, `scan_metrics`, generated by the real route over a temporary ledger. The metrics files are written by the
real recorder (runtime/scan_metrics.py: the same hooks, phases and document the calibration worker uses, on a scripted fixed clock) and sealed the way the
worker's operation seals them (result_refs with the file's sha256); nothing is typed by hand and nothing here is the live ledger or a device.

  read        GET /api/calibrate/metrics[?operation_id=]  ->  {operation, metrics[, artifact_errors]}. The operation is the one named, else the latest calibration or
              observation of the selected emulator and account, exactly as /api/calibrate/status. `metrics` is the sealed calibrate_metrics.json (schema_version,
              operation_id, run, closed, started_at, ended_at, duration_s, exit, phases[], ocr, captures, inputs, errors, start_state, identity, hook_errors); it is null for an
              operation that sealed none (an older worker, a worker that died before writing, one still running) and for no operation at all (operation null).
  run         what was asked and on what: the operation's kind and request (phases, fresh, overwrite, routes, flows), its account, device_key, rendering and instance, read by
              the recorder from the operation's ledger record. A later comparison judges a pair from the two files alone with it and `identity`.
  phases      each phase says whether it ran in this operation (a phase the saved state already held done is `carried_over` with no coverage and no duration), its
              duration, the OCR calls, captures and inputs it caused, its coverage (the phase's own returned result flattened to counts) and its errors.
  identity    revision, fingerprint, measured files, the Python version and the Windows build, and a tree_state: clean (equal to a side declared in backend/logs/scan_sides.json),
              dirty (the revision is declared and the fingerprint matches no side) or undeclared. The Python version and the Windows build are facts of the machine that generates
              the sample: `pin_host` fixes them in the world (Python 3.12.0, Windows 10.0.26100), as the runtime families pin theirs.
  damaged     a file that changed after it was sealed, or that is not valid JSON, or that names another operation is not shown: `metrics` stays null and
              `artifact_errors.metrics` carries the reason (the file changed after it was sealed; it is not valid JSON; it belongs to another operation).
  refusals    an unknown operation and an operation of another workflow are 409 {ok:false, code, error[, operation]}, as the status route.

Not recorded (no producer): a file whose write failed (there is no file), and a newer schema_version (only a newer worker writes one).
"""
import hashlib
import json
from pathlib import Path

from dashboard_contract_cases_calibrate import seal
from runtime import scan_identity, scan_metrics

SM = 'scan_metrics'
URL = '/api/calibrate/metrics'
SIDES = {'after': dict(source_revision='a' * 40, source_fingerprint='f' * 64, overlay_hash=None),
         'before': dict(source_revision='a' * 40, source_fingerprint='e' * 64, overlay_hash='b' * 64)}
FAILED = {'code': 'capture_incomplete', 'message': 'Not every requested phase has a confirmed completed result'}
CARDS = {'card_presets': ['a'] * 5, 'names': ['a'] * 5, 'inventory': {'complete': True, 'cards': [{}] * 31, 'pages': 7, 'unreadable_tiles': 0, 'active': 20, 'mastered': 0}}
MODULES = {'modules_equipped': ['a'] * 4, 'modules_in_grid': ['a'] * 26, 'copies': 52, 'preset_tabs': ['a'] * 2}


class Clock:
    def __init__(self):
        self.now = 1_800_000_000.0

    def __call__(self):
        return self.now

    def advance(self, seconds):
        self.now += seconds


def pin_host(w):
    """The interpreter and Windows build the identity block reports are facts of the machine: fix them (scan_identity.host provides the public host identity)."""
    w.mp.setattr(scan_identity, 'host', lambda: dict(python='3.12.0', windows='10.0.26100'))


def bind_account(w):
    """The world's emulator renders at the native size and its instance is bound to an account, so the run block names both (an unbound world reports null)."""
    def change(cfg):
        cfg['accounts'] = {'alpha': {'label': 'Alpha', 'active_profile': 'mine', 'loadouts': {}}}
        cfg['instances']['main']['account'] = 'alpha'
        cfg['instances']['main']['rendering'] = dict(width=1080, height=2560, dpi=360)
    w.edit_config(change)


def identity(fingerprint='f' * 64):
    """A worker's identity block on the world's fixed sides: the revision and fingerprint it loaded, measured files with fixed hashes, the pinned host."""
    return dict(source_revision='a' * 40, source_fingerprint=fingerprint, build_error=None,
                measured_files={rel: hashlib.sha256(rel.encode()).hexdigest() for rel in scan_identity.MEASURED_FILES},
                **scan_identity.host(), **scan_identity.classify(SIDES, 'a' * 40, fingerprint))


def sealed_by(w, make, **kwargs):
    """The file a worker of this world writes: `make` is given the operation id and the run block the recorder reads from the operation's own ledger record."""
    return lambda operation_id: make(operation_id, scan_metrics.run_of(w.store.get(operation_id)), **kwargs)


def two_phase(operation_id, run, *, fingerprint='f' * 64, carried=False, failing=False):
    """A scan of cards and modules written by the real recorder: taps, a swipe, OCR, captures and the coverage each phase returned."""
    clock = Clock()
    scan_metrics.begin(operation_id, identity(fingerprint), run, mono=clock, wall=clock)
    scan_metrics.set_start_state(dict(templates=dict(digest='c' * 64, count=184), phases_done=['cards'] if carried else []))
    if carried:
        scan_metrics.phase_carried_over('cards')
    else:
        scan_metrics.phase_begin('cards')
        for _ in range(3):
            scan_metrics.capture_ok()
        scan_metrics.ocr_call(1)
        scan_metrics.ocr_launch()
        scan_metrics.tap('open cards')
        scan_metrics.swipe('card calibration: preserve a complete inventory row')
        clock.advance(98.5)
        scan_metrics.phase_end('cards', 'done', coverage=scan_metrics.coverage_of_result(CARDS))
    scan_metrics.phase_begin('modules')
    scan_metrics.capture_ok()
    scan_metrics.capture_retry()
    scan_metrics.ocr_call(2)
    scan_metrics.ocr_launch()
    scan_metrics.ocr_timeout()
    scan_metrics.tap('starter scan: inspect captured inventory tile')
    scan_metrics.input_refused()
    clock.advance(127.25)
    if failing:
        scan_metrics.phase_end('modules', 'error', error='The module grid did not settle', unverified=['modules/diamond_nanowall.png'])
        return scan_metrics.end().document('raised', RuntimeError('The module grid did not settle'))
    scan_metrics.phase_end('modules', 'done', coverage=scan_metrics.coverage_of_result(MODULES, {'module_inventory_complete': True}))
    return scan_metrics.end().document()


def bootstrap(operation_id, run):
    clock = Clock()
    scan_metrics.begin(operation_id, identity(), run, mono=clock, wall=clock)
    scan_metrics.set_start_state(dict(templates=dict(digest='c' * 64, count=184), phases_done=[]))
    started = clock()
    state = {'phases': {'bootstrap': {'kind': 'routes', 'completed': 5, 'total': 5, 'screens': ['home', 'perks_hub', 'perks_first'], 'skipped': [], 'needs_attention': 0}},
             'screen_map': {'home': {'status': 'verified', 'verified': 8, 'total': 8}, 'perks_hub': {'status': 'verified', 'verified': 2, 'total': 2}, 'perks_first': {'status': 'verified', 'verified': 1, 'total': 1}},
             'entries': [{'t': started + 1, 'verified': True}] * 5}
    with scan_metrics.phase('bootstrap', coverage=lambda: scan_metrics.bootstrap_coverage(state, started), status=lambda: 'done'):
        scan_metrics.capture_ok()
        scan_metrics.tap('manifest scan: open perks')
        clock.advance(19.5)
    return scan_metrics.end().document()


def read(w, case, query=''):
    return w.get(SM, case, URL + query)


def scan_metrics_cases(gen):
    with gen.world('metrics_clean') as w:
        pin_host(w)
        bind_account(w)
        request = {'phases': 'c,m', 'fresh': True, 'overwrite': False}
        op = seal(w, request=request, state=dict(phases=dict(cards=dict(status='done'), modules=dict(status='done'))), files={'calibrate_metrics.json': sealed_by(w, two_phase)})
        got = read(w, 'read_the_metrics_of_a_clean_two_phase_scan', '?operation_id=' + op['id']).get_json()
        doc = got['metrics']
        assert got['operation']['id'] == op['id'] and doc['operation_id'] == op['id'] and doc['closed'] is True and doc['identity']['tree_state'] == 'clean' and doc['identity']['side'] == 'after'
        context = op['context']
        assert doc['run'] == dict(kind='calibrate', request=request, account=context['account'], device_key=context['device_key'], rendering=context['rendering'], instance='main')
        assert doc['run']['account'] == 'alpha' and doc['run']['rendering'] == dict(width=1080, height=2560, dpi=360) and doc['run']['device_key']
        assert doc['identity']['python'] == '3.12.0' and doc['identity']['windows'] == '10.0.26100'
        cards, modules = doc['phases']
        assert cards['ran_in_this_operation'] and cards['duration_s'] == 98.5 and cards['coverage']['inventory']['cards'] == 31 and cards['inputs'] == dict(taps=1, swipes=1, refused=0, by_reason={'open cards': 1, 'card calibration: preserve a complete inventory row': 1})
        assert modules['captures'] == dict(ok=1, retries=1, failed=0) and modules['ocr'] == dict(calls=1, crops=2, process_launches=1, timeouts=1, errors=0) and modules['inputs']['refused'] == 1
        assert modules['coverage']['module_inventory_complete'] is True and doc['captures']['ok'] == 4 and doc['ocr']['calls'] == 2 and 'artifact_errors' not in got
        assert doc == json.loads(Path(op['result_refs']['calibrate_metrics.json']['path']).read_text(encoding='utf-8')), 'the route shows exactly the sealed file'
        status = w.get(SM, 'status_with_sealed_scan_metrics',
                          '/api/calibrate/status?operation_id=' + op['id'])
        assert 'calibrate_metrics.json' in status.get_json()['operation']['result_refs']
        latest = read(w, 'read_the_latest_calibration_of_the_context_reads_its_metrics').get_json()
        assert latest['metrics'] == doc
    with gen.world('metrics_carried') as w:
        pin_host(w)
        op = seal(w, state=dict(phases=dict(cards=dict(status='done'), modules=dict(status='done'))), files={'calibrate_metrics.json': sealed_by(w, two_phase, fingerprint='d' * 64, carried=True)})
        doc = read(w, 'read_a_scan_that_carried_a_phase_over_on_a_dirty_tree', '?operation_id=' + op['id']).get_json()['metrics']
        assert doc['phases'][0]['status'] == 'carried_over' and doc['phases'][0]['ran_in_this_operation'] is False and doc['phases'][0]['coverage'] == {} and doc['phases'][0]['duration_s'] == 0.0
        assert doc['identity']['tree_state'] == 'dirty' and doc['identity']['side'] is None and doc['start_state']['phases_done'] == ['cards']
    with gen.world('metrics_failed') as w:
        pin_host(w)
        op = seal(w, status='failed', error=FAILED, state=dict(phases=dict(cards=dict(status='done'), modules=dict(status='error', error='The module grid did not settle'))),
                  files={'calibrate_metrics.json': sealed_by(w, two_phase, failing=True)})
        got = read(w, 'read_a_failed_scan_keeps_its_metrics_and_errors', '?operation_id=' + op['id']).get_json()
        doc = got['metrics']
        assert got['operation']['status'] == 'failed' and doc['exit']['outcome'] == 'raised' and doc['exit']['error']['message'] == 'The module grid did not settle'
        assert [(e['phase'], e['kind']) for e in doc['errors']] == [('modules', 'error'), ('modules', 'entries_not_verified')] and doc['phases'][1]['status'] == 'error'
    with gen.world('metrics_bootstrap') as w:
        pin_host(w)
        op = seal(w, state=dict(phases=dict(bootstrap=dict(status='done'))), request={'bootstrap': True, 'routes': ['route_23', 'route_24']}, files={'calibrate_metrics.json': sealed_by(w, bootstrap)})
        doc = read(w, 'read_the_metrics_of_a_bootstrap_scan_with_its_screens', '?operation_id=' + op['id']).get_json()['metrics']
        assert doc['run']['request'] == {'bootstrap': True, 'routes': ['route_23', 'route_24']} and doc['run']['kind'] == 'calibrate'
        (phase,) = doc['phases']
        assert phase['name'] == 'bootstrap' and phase['coverage']['screens'] == ['home', 'perks_first', 'perks_hub'] and phase['coverage']['targets'] == dict(total=5, verified=5)
    with gen.world('metrics_none') as w:
        op = seal(w, state=dict(phases=dict(cards=dict(status='done'))))
        got = read(w, 'read_a_scan_that_sealed_no_metrics_has_none', '?operation_id=' + op['id']).get_json()
        assert got['metrics'] is None and got['operation']['id'] == op['id'] and 'artifact_errors' not in got
    with gen.world('metrics_nothing') as w:
        assert read(w, 'read_with_no_calibration_at_all_answers_no_operation').get_json() == dict(operation=None, metrics=None)
    with gen.world('metrics_observe') as w:
        pin_host(w)
        op = seal(w, kind='observe', state=dict(phases=dict(bootstrap=dict(status='done'))), request={}, files={'calibrate_metrics.json': sealed_by(w, bootstrap)})
        doc = read(w, 'read_the_metrics_of_an_observation', '?operation_id=' + op['id']).get_json()['metrics']
        assert doc['run']['kind'] == 'observe' and doc['run']['request'] == {} and doc['operation_id'] == op['id']
    with gen.world('metrics_changed') as w:
        pin_host(w)
        op = seal(w, state=dict(phases=dict(cards=dict(status='done'))), files={'calibrate_metrics.json': sealed_by(w, two_phase)})
        Path(op['result_refs']['calibrate_metrics.json']['path']).write_text(json.dumps(dict(operation_id=op['id'], closed=True, forged=True)), encoding='utf-8')
        got = read(w, 'read_metrics_changed_after_they_were_sealed_are_named_and_not_shown', '?operation_id=' + op['id']).get_json()
        assert got['metrics'] is None and 'changed' in got['artifact_errors']['metrics']
    with gen.world('metrics_foreign') as w:
        pin_host(w)
        op = seal(w, state=dict(phases=dict(cards=dict(status='done'))), files={'calibrate_metrics.json': sealed_by(w, lambda op_id, run: two_phase('another-operation', run))})
        got = read(w, 'read_metrics_of_another_operation_are_not_shown', '?operation_id=' + op['id']).get_json()
        assert got['metrics'] is None and 'another operation' in got['artifact_errors']['metrics']
    with gen.world('metrics_invalid') as w:
        op = seal(w, state=dict(phases=dict(cards=dict(status='done'))), files={'calibrate_metrics.json': b'{"operation_id": "cut off'})
        got = read(w, 'read_metrics_that_are_not_valid_json_are_named_and_not_shown', '?operation_id=' + op['id']).get_json()
        assert got['metrics'] is None and got['artifact_errors']['metrics'] == 'Saved calibrate_metrics.json is not valid JSON' and 'another operation' not in got['artifact_errors']['metrics']
    with gen.world('metrics_refusals') as w:
        reply = read(w, 'read_an_unknown_operation_is_refused_409', '?operation_id=no-such-operation')
        assert reply.status_code == 409 and reply.get_json()['code'] == 'operation_unknown'
        run = w.running('run', {'preset': 'bp_farm'}, args=['--preset', 'bp_farm'])
        reply = read(w, 'read_an_operation_of_another_workflow_is_refused_409', '?operation_id=' + run['id'])
        assert reply.status_code == 409 and reply.get_json()['code'] == 'operation_kind_mismatch'


